class Solution {
    void pushZerosToEnd(int[] arr) {
        int j = 0;
        // code here
        int n = arr.length;
        for(int  i=0; i<n; i++){
            if(arr[i] != 0){
                int temp = arr[i];
                arr[i] = arr[j];
                arr[j] = temp;
                j++;

            }
        }
    }
}

